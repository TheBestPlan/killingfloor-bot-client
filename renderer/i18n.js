  const DICT = { en, ru, es, pt, lt, pl, fr, zh, ja };
  const hooks = [];
  let cur = 'en';

  // {name} placeholders are filled from vars; an unknown key renders itself, so a typo is visible
  // rather than silently blank.
  function t(key, vars) {
    let s = DICT[cur][key];
    if (s == null) s = en[key];
    if (s == null) return key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m)) : s;
  }
  const el = (x) => (typeof x === 'string' ? document.getElementById(x) : x);
  const argsOf = (node) => { try { return node.dataset.i18nArgs ? JSON.parse(node.dataset.i18nArgs) : null; } catch (e) { return null; } };

  // Script-written text keeps its key on the element, so a language switch re-renders it too.
  function setText(target, key, vars) {
    const node = el(target); if (!node) return;
    node.dataset.i18n = key;
    if (vars) node.dataset.i18nArgs = JSON.stringify(vars); else delete node.dataset.i18nArgs;
    node.textContent = t(key, vars);
  }
  function setPlaceholder(target, key) {
    const node = el(target); if (!node) return;
    node.dataset.i18nPh = key;
    node.placeholder = t(key);
  }

  function apply(lang) {
    cur = DICT[lang] ? lang : 'en';
    document.documentElement.lang = cur;
    document.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n, argsOf(n)); });
    document.querySelectorAll('[data-i18n-html]').forEach((n) => { n.innerHTML = t(n.dataset.i18nHtml); });
    document.querySelectorAll('[data-i18n-title]').forEach((n) => { n.title = t(n.dataset.i18nTitle); });
    document.querySelectorAll('[data-i18n-ph]').forEach((n) => { n.placeholder = t(n.dataset.i18nPh); });
    hooks.forEach((f) => { try { f(cur); } catch (e) { /* a hook must not break the switch */ } });
  }

  return {
    LANGS, DICT, t, apply, setText, setPlaceholder,
    onChange: (fn) => hooks.push(fn),
    get lang() { return cur; },
  };
